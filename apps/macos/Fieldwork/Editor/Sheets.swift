struct AddSectionSheet: View {
    @ObservedObject var model: EditorModel
    @Environment(\.dismiss) private var dismiss
    @State private var name = "Trumpet"
    @State private var prefix = "T"
    @State private var count = 8
    @State private var symbol: PerformerSymbol = .circle

    var body: some View {
        Form {
            Text("Add a section").font(.headline)
            LabeledContent("Section") {
                InstrumentPicker(name: $name, prefix: $prefix).labelsHidden()
            }
            TextField("Label letter", text: $prefix)
            if let existing = model.show.sections.first(where: { $0.name.caseInsensitiveCompare(name.trimmingCharacters(in: .whitespaces)) == .orderedSame }) {
                Text("Adds performers to the existing \(existing.name) section, continuing its \(existing.prefix) labels.")
                    .font(.caption).foregroundStyle(Color.fwSecondary)
            } else if let clash = model.show.sections.first(where: { $0.prefix == prefix }) {
                Label("\(clash.name) already uses \(prefix). Labels stay unique but will be hard to tell apart.", systemImage: "exclamationmark.triangle")
                    .font(.caption).foregroundStyle(Color.fwWarning)
            }
            Stepper("\(count) performers", value: $count, in: 1...400)
            Picker("Symbol", selection: $symbol) {
                ForEach(PerformerSymbol.allCases, id: \.self) { Text($0.rawValue.capitalized).tag($0) }
            }
            Text("New performers start without positions at every set, so nothing is placed by accident.")
                .font(.caption).foregroundStyle(Color.fwSecondary)
            HStack {
                Spacer()
                Button("Cancel") { dismiss() }.keyboardShortcut(.cancelAction)
                Button("Add") {
                    model.addSection(name: name, prefix: prefix, count: count, symbol: symbol)
                    dismiss()
                }
                .keyboardShortcut(.defaultAction)
                .disabled(name.trimmingCharacters(in: .whitespaces).isEmpty || prefix.isEmpty)
            }
        }
        .padding(Tokens.Space.xl)
        .frame(width: 380)
    }
}

/// Coordinate PDF preview generated by the portable exporter, shown in PDFKit.
struct ExportSheet: View {
    @ObservedObject var model: EditorModel
    @Environment(\.dismiss) private var dismiss
    @State private var rounding = 0.25
    @State private var includeCharts = true
    @State private var includeNames = false
    @State private var pdf: Data?
    @State private var error: String?

    var body: some View {
        VStack(alignment: .leading, spacing: Tokens.Space.m) {
            HStack {
                Text("Coordinate sheets").font(.headline)
                Spacer()
                Picker("Rounding", selection: $rounding) {
                    Text("¼ step").tag(0.25)
                    Text("½ step").tag(0.5)
                    Text("1 step").tag(1.0)
                }
                .frame(width: 160)
                Toggle("Set charts", isOn: $includeCharts)
                Toggle("Private names", isOn: $includeNames)
                    .help("Roster names are left out of shareable output unless you include them")
            }
            if let error {
                Label(error, systemImage: "exclamationmark.triangle.fill").foregroundStyle(Color.fwWarning)
                Spacer()
            } else if let pdf {
                PDFPreview(data: pdf)
                    .frame(minHeight: 420)
                    .accessibilityLabel("Coordinate sheet preview")
            } else {
                ProgressView()
                Spacer()
            }
            HStack {
                Text(model.selection.isEmpty ? "All \(model.show.performers.count) performers" : "\(model.selection.count) selected performers")
                    .foregroundStyle(Color.fwSecondary)
                Spacer()
                Button("Close") { dismiss() }.keyboardShortcut(.cancelAction)
                Button("Export PDF…") { save() }.keyboardShortcut(.defaultAction).disabled(pdf == nil)
            }
        }
        .padding(Tokens.Space.xl)
        .frame(width: 720, height: 640)
        .onAppear(perform: render)
        .onChange(of: rounding) { _, _ in render() }
        .onChange(of: includeCharts) { _, _ in render() }
        .onChange(of: includeNames) { _, _ in render() }
    }

    private func render() {
        let ids = model.selection.isEmpty ? nil : model.show.performers.map(\.id).filter { model.selection.contains($0) }
        do {
            pdf = try model.coordinatePDF(options: CoordinateExportOptions(performerIDs: ids, rounding: rounding, includeNames: includeNames, includeSetCharts: includeCharts))
            error = nil
        } catch {
            pdf = nil
            self.error = "\(error)"
        }
    }

    private func save() {
        guard let pdf else { return }
        let panel = NSSavePanel()
        panel.allowedContentTypes = [.pdf]
        panel.nameFieldStringValue = "\(model.show.title) coordinates.pdf"
        if panel.runModal() == .OK, let url = panel.url {
            do { try pdf.write(to: url, options: .atomic) } catch {
                model.alert = EditorAlert(title: "Export failed", message: "Could not write \(url.lastPathComponent): \(error.localizedDescription)")
            }
        }
    }
}

struct PDFPreview: NSViewRepresentable {
    var data: Data

    func makeNSView(context: Context) -> PDFView {
        let view = PDFView()
        view.autoScales = true
        view.displayMode = .singlePageContinuous
        return view
    }

    func updateNSView(_ view: PDFView, context: Context) {
        if view.document?.dataRepresentation() != data { view.document = PDFDocument(data: data) }
    }
}
